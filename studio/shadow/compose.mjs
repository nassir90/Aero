import puppeteer from 'puppeteer-core';
const [id, ...flags] = process.argv.slice(2);
const SINK = process.env.SINK || 'http://127.0.0.1:8785';
const CHROME = process.env.CHROME || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome';
const browser = await puppeteer.launch({ executablePath: CHROME, headless: true, protocolTimeout: 3.6e6, args: ['--use-angle=metal', '--enable-gpu', '--ignore-gpu-blocklist'] });
const page = await browser.newPage();
page.on('pageerror', e => console.error('pageerror', e.message));
page.on('console', m => { if (m.type() === 'error') console.error('console', m.text()); });
await page.goto(SINK + '/compose.html', { waitUntil: 'networkidle0' });
await page.evaluate(() => document.fonts.load('400 40px "Times New Roman"'));
const t0 = Date.now();
const res = await page.evaluate(async (id, prev) => { await COMPOSE.run(id, prev ? { preview: true, every: 30 } : {}); return JSON.stringify({ frames: STATUS.of, crowd: STATUS.crowd, overrun: STATUS.overrun || null, subLines: STATUS.subLines, callMotion: STATUS.callMotion }); }, id, flags.includes('--preview'));
console.log(res); console.log(((Date.now() - t0) / 1000).toFixed(0) + 's');
await Promise.race([browser.close(), new Promise(r => setTimeout(r, 4000))]);
process.exit(0);
